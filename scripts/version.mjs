import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

export function isoWeek(date) {
  const d = new Date(Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), date.getUTCDate()));
  if (Number.isNaN(d.getTime())) throw new Error('Invalid release date');
  d.setUTCDate(d.getUTCDate() + 4 - (d.getUTCDay() || 7));
  const year = d.getUTCFullYear();
  const week = Math.ceil((((d - new Date(Date.UTC(year, 0, 1))) / 86400000) + 1) / 7);
  return { year, week };
}
export function parseVersion(version) {
  const m = /^(20\d{2})\.([1-9]|[1-4]\d|5[0-3])\.(0|[1-9]\d*)$/.exec(version);
  if (!m) throw new Error('Version must use YYYY.W.N without leading zeros');
  const [year, week, patch] = m.slice(1).map(Number);
  if (week > isoWeek(new Date(Date.UTC(year, 11, 28))).week || patch > 65535) throw new Error('Version is outside the ISO-week/MSI range');
  return { year, week, patch };
}
export function nextVersion(date, versions) {
  const { year, week } = isoWeek(date);
  const prefix = `${year}.${week}.`;
  const patches = versions.map(v => v.replace(/^v/, '')).filter(v => v.startsWith(prefix))
    .map(v => { try { return parseVersion(v).patch; } catch { return -1; } });
  return prefix + (Math.max(-1, ...patches) + 1);
}

const packagePaths = ['package.json', 'packages/embed/package.json', 'mcp-server/package.json'];
const lockPaths = ['package-lock.json', 'mcp-server/package-lock.json'];
const json = path => JSON.parse(readFileSync(path, 'utf8'));
const writeJson = (path, data) => writeFileSync(path, JSON.stringify(data, null, 2) + '\n');
function versions() {
  return [...packagePaths.map(path => [path, json(path).version]),
    ['src-tauri/tauri.conf.json', json('src-tauri/tauri.conf.json').version],
    ['src-tauri/Cargo.toml', /^version = "([^"]+)"/m.exec(readFileSync('src-tauri/Cargo.toml', 'utf8'))[1]],
    ...lockPaths.filter(existsSync).flatMap(path => [[path, json(path).version], [path + ':root', json(path).packages[''].version]]),
    ...(existsSync('src-tauri/Cargo.lock') ? [['src-tauri/Cargo.lock', /name = "open-calc-studio"\nversion = "([^"]+)"/.exec(readFileSync('src-tauri/Cargo.lock', 'utf8'))?.[1]]] : [])];
}
function set(version) {
  const { year, week, patch } = parseVersion(version);
  for (const path of packagePaths) writeJson(path, { ...json(path), version });
  for (const path of lockPaths.filter(existsSync)) {
    const lock = json(path); lock.version = version; lock.packages[''].version = version; lock.packages[''].license = 'LGPL-3.0-only'; writeJson(path, lock);
  }
  const config = json('src-tauri/tauri.conf.json'); config.version = version;
  config.bundle.windows.wix = { ...config.bundle.windows.wix, version: `${year - 2000}.${week}.${patch}` };
  writeJson('src-tauri/tauri.conf.json', config);
  const cargo = 'src-tauri/Cargo.toml';
  writeFileSync(cargo, readFileSync(cargo, 'utf8').replace(/^version = "[^"]+"/m, `version = "${version}"`));
  const lock = 'src-tauri/Cargo.lock';
  if (existsSync(lock)) writeFileSync(lock, readFileSync(lock, 'utf8').replace(/(name = "open-calc-studio"\nversion = ")[^"]+/, `$1${version}`));
  writeFileSync('mcp-server/src/version.ts', `// Generated by scripts/version.mjs\nexport const APP_VERSION = '${version}';\n`);
  console.log(`All product packages: ${version}; MSI: ${year - 2000}.${week}.${patch}`);
}
function main() {
  const [command = 'check', value] = process.argv.slice(2);
  if (command === 'set') return set(value);
  if (command === 'next') {
    const tags = execFileSync('git', ['tag', '--list', 'v20*'], { encoding: 'utf8' }).trim().split('\n');
    return set(nextVersion(value ? new Date(value) : new Date(), [json('package.json').version, ...tags]));
  }
  if (command !== 'check') throw new Error('Use version.mjs check [tag], set YYYY.W.N, or next [date]');
  const version = json('package.json').version;
  const { year, week, patch } = parseVersion(version);
  for (const [path, actual] of versions()) if (actual !== version) throw new Error(`${path}: ${actual} != ${version}`);
  if (!readFileSync('mcp-server/src/version.ts', 'utf8').includes(`APP_VERSION = '${version}'`)) throw new Error('MCP runtime version differs');
  const msi = `${year - 2000}.${week}.${patch}`;
  if (json('src-tauri/tauri.conf.json').bundle.windows.wix?.version !== msi) throw new Error(`MSI must use ${msi}`);
  if (value && value !== `v${version}`) throw new Error(`Release tag ${value} != v${version}`);
  console.log(`Version ${version} is consistent across all packages; MSI ${msi}.`);
}
if (resolve(process.argv[1] || '') === fileURLToPath(import.meta.url)) main();
